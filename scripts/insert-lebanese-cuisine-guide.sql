## 🌟 Regional Variations in Lebanese Cooking

Lebanese cuisine varies by region:

**Coastal Areas (Beirut, Sidon, Tyre):**
- More seafood dishes like sayadieh
- Fresh fish grilled or baked with tahini sauce

**Mountain Regions (Mount Lebanon):**
- Heartier stews and preserved foods
- More lamb and dairy products

**Bekaa Valley:**
- Agricultural abundance leads to vegetable-focused dishes
- Famous for arak production

**Northern Lebanon (Tripoli):**
- Sweeter desserts and pastries
- Unique dishes like kubba (different from kibbeh)

